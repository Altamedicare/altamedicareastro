#!/usr/bin/env node
// gen-rx-directory.mjs — regenerates the #all-medications directory inside
// public/prescription-drug-assistance.html from the medication-assistance
// record registry (src/data/medicationAssistance/*.ts), grouped by clinical
// condition (src/data/conditions.ts order). The finder is a static public
// file, so this keeps its crawlable directory in lockstep with the registry
// instead of a hand-maintained list that goes stale as medications are added.
//
//   node scripts/gen-rx-directory.mjs           # rewrite the section
//   node scripts/gen-rx-directory.mjs --check   # exit 1 if out of sync (build gate)
//
// The section lives between the rx-directory:start / rx-directory:end markers.
// Record fields are read with anchored regexes rather than a TS import so the
// script stays dependency-free (records are uniform literal objects).
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = join(root, 'src', 'data', 'medicationAssistance');
const finderPath = join(root, 'public', 'prescription-drug-assistance.html');

const NON_RECORDS = new Set(['index.ts', 'shared.ts', 'categories.ts', 'drugClasses.ts']);

function fieldStr(src, name, file) {
  const m = src.match(new RegExp(`\\b${name}:\\s*'((?:[^'\\\\]|\\\\.)*)'`));
  if (!m) throw new Error(`${file}: could not read ${name}`);
  return m[1].replace(/\\'/g, "'");
}
function fieldArr(src, name, file) {
  const m = src.match(new RegExp(`\\b${name}:\\s*\\[([^\\]]*)\\]`));
  if (!m) throw new Error(`${file}: could not read ${name}`);
  return [...m[1].matchAll(/'([^']+)'/g)].map((x) => x[1]);
}

const records = readdirSync(dataDir)
  .filter((f) => f.endsWith('.ts') && !NON_RECORDS.has(f))
  .map((f) => {
    const src = readFileSync(join(dataDir, f), 'utf8');
    return {
      slug: fieldStr(src, 'slug', f),
      brand: fieldStr(src, 'brandName', f),
      generic: fieldStr(src, 'genericName', f),
      conditions: fieldArr(src, 'conditions', f),
    };
  });

const condSrc = readFileSync(join(root, 'src', 'data', 'conditions.ts'), 'utf8');
const conditions = [...condSrc.matchAll(
  /\{\s*key:\s*'([^']+)',\s*label:\s*(?:'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)")\s*\}/g,
)].map((m) => ({ key: m[1], label: (m[2] ?? m[3]).replace(/\\'/g, "'").trim() }));
if (conditions.length < 10) throw new Error('conditions.ts: parse failure');

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const groups = conditions
  .map((c) => ({
    ...c,
    drugs: records
      .filter((r) => r.conditions.includes(c.key))
      .sort((a, b) => a.brand.localeCompare(b.brand)),
  }))
  .filter((g) => g.drugs.length > 0);

const grouped = groups
  .map(
    (g) =>
      `      <h3 style="margin:22px 0 10px;font-size:1.02rem;color:var(--ink)">${esc(g.label)}</h3>\n` +
      `      <div class="pop-links">\n` +
      g.drugs
        .map(
          (r) =>
            `        <a href="/${r.slug}-assistance-program"><i class="fa-solid fa-hand-holding-dollar"></i> ${esc(r.brand)} <span style="color:var(--muted);font-weight:400">(${esc(r.generic)})</span></a>`,
        )
        .join('\n') +
      `\n      </div>`,
  )
  .join('\n');

const START = '<!-- rx-directory:start (generated by scripts/gen-rx-directory.mjs — do not edit by hand) -->';
const END = '<!-- rx-directory:end -->';

const section = `${START}
  <section class="block" id="all-medications">
    <h2><i class="fa-solid fa-pills"></i> All Medication Assistance Guides</h2>
    <p style="color:var(--ink-soft);max-width:72ch;margin:6px 0 4px">Every medication below has its own researched guide: the manufacturer's programs, charitable funds, what Medicare enrollees can and cannot use, and how to apply — each claim checked on its official source. ${records.length} medications; one appears under each condition it treats.</p>
${grouped}
  </section>
  ${END}`;

let html = readFileSync(finderPath, 'utf8');
const re = new RegExp(
  `${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`,
);

if (!re.test(html)) {
  console.error('gen-rx-directory: markers not found in public/prescription-drug-assistance.html');
  process.exit(1);
}

const next = html.replace(re, section);

if (process.argv.includes('--check')) {
  if (next !== html) {
    console.error(
      `gen-rx-directory: #all-medications directory is OUT OF SYNC with the record registry (${records.length} records). Run: node scripts/gen-rx-directory.mjs`,
    );
    process.exit(1);
  }
  console.log(`  rx directory OK — ${records.length} medications, ${groups.length} condition groups`);
} else {
  writeFileSync(finderPath, next);
  console.log(`gen-rx-directory: wrote ${records.length} medications in ${groups.length} condition groups`);
}
